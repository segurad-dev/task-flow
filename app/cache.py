"""Клиент Redis для кэширования данных приложения.

Redis используется для кэширования списка задач пользователя.
Стратегия: cache-aside (ленивая загрузка):
  1. Запрос → проверить Redis
  2. Если есть (cache hit) → вернуть из Redis, не ходить в БД
  3. Если нет (cache miss) → загрузить из БД, сохранить в Redis
  4. При изменении данных → явно удалить кэш (инвалидация)

Ключ кэша: tasks:{user_id}
  - У каждого пользователя свой независимый кэш
  - При инвалидации удаляем только кэш конкретного пользователя

TTL: 60 секунд
  - Баланс между актуальностью данных и нагрузкой на БД
  - Даже при сбое инвалидации кэш протухнет через 60 секунд
"""

import redis.asyncio as aioredis

from app.config import settings

# from_url создаёт пул соединений к Redis.
# decode_responses=True: Redis хранит всё как bytes,
# но с этим флагом автоматически декодирует в str.
# Без него get() вернул бы b'...' вместо '...' и json.loads упал бы.
redis_client = aioredis.from_url(settings.REDIS_URL, decode_responses=True)
